#!/usr/bin/env python3

###
# Write a C context file for m2c from the same model gen_headers.py uses.
#
# m2c only parses C, so classes become flat C structs (bases and the vtable
# pointer inlined at their offsets) named exactly like the demangled class, so
# m2c's C++ mode types `this` and class parameters with them. Inferred fields
# whose type is uncertain use UNK_TYPE*, and gaps are `char unk_XX[n]`, both of
# which m2c treats as space it may refine.
#
#   python tools/m2c_context.py [-o build/m2c/context.c]
###

import argparse
import sys
from pathlib import Path
from typing import List, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_headers import ROOT, ClassInfo, Emitter, Model  # noqa: E402

PRELUDE = """\
/* m2c context generated by tools/m2c_context.py; do not edit. */
typedef signed char s8;
typedef signed short s16;
typedef signed long s32;
typedef signed long long s64;
typedef unsigned char u8;
typedef unsigned short u16;
typedef unsigned long u32;
typedef unsigned long long u64;
typedef float f32;
typedef double f64;
typedef int BOOL;
typedef s8 UNK_TYPE1;
typedef s16 UNK_TYPE2;
typedef s32 UNK_TYPE4;
typedef unsigned long size_t;
typedef s64 OSTime;
typedef u32 OSTick;

/* Dolphin SDK / C library functions with well-known signatures.
   Variadic ones (OSReport, printf...) are left out on purpose: with a
   prototype m2c passes every live register as an extra argument. */
void* OSGetArenaLo(void);
void* OSGetArenaHi(void);
void OSSetArenaLo(void* addr);
void OSSetArenaHi(void* addr);
BOOL OSDisableInterrupts(void);
BOOL OSEnableInterrupts(void);
BOOL OSRestoreInterrupts(BOOL level);
OSTime OSGetTime(void);
OSTick OSGetTick(void);
void DCFlushRange(void* addr, u32 nBytes);
void DCInvalidateRange(void* addr, u32 nBytes);
void DCStoreRange(void* addr, u32 nBytes);
void ICInvalidateRange(void* addr, u32 nBytes);
void* memcpy(void* dst, const void* src, size_t n);
void* memset(void* dst, int c, size_t n);
int memcmp(const void* a, const void* b, size_t n);
size_t strlen(const char* s);
char* strcpy(char* dst, const char* src);
char* strncpy(char* dst, const char* src, size_t n);
char* strcat(char* dst, const char* src);
int strcmp(const char* a, const char* b);
int strncmp(const char* a, const char* b, size_t n);
char* strchr(const char* s, int c);
char* strstr(const char* s, const char* sub);
int atoi(const char* s);
double atof(const char* s);
"""

FIELD_C = {"u8": "UNK_TYPE1", "u16": "UNK_TYPE2", "s16": "s16", "u32": "UNK_TYPE4",
           "void*": "void*", "f32": "f32"}


def flat_fields(em: Emitter, info: ClassInfo, base_off: int = 0, seen=()) -> List[Tuple[int, int, str, str]]:
    """(offset, size, ctype, name) for a class including its bases."""
    m = em.m
    out: List[Tuple[int, int, str, str]] = []
    if info.path in seen:
        return out
    for b, off in info.bases:
        if b in m.classes:
            out += flat_fields(em, m.classes[b], base_off + off, seen + (info.path,))
    start = m.own_start(info)
    end = info.size if info.size is not None else m.extent(info)
    if m.introduces_vptr(info):
        vptr = info.vptr if info.vptr is not None else start
        out.append((base_off + vptr, 4, "void*", "__vtable"))
    for off, size, decl in em.fields(info, start, end):
        ty, name = decl.split(";")[0].rsplit(" ", 1)
        if name.endswith("[2]"):
            name = name[:-3]
            ctype = "u32" if "lfd" in decl else "f32"
            out.append((base_off + off, size, ctype, name + "[2]"))
        else:
            out.append((base_off + off, size, FIELD_C.get(ty, ty), name))
    return out


def struct_text(em: Emitter, info: ClassInfo) -> str:
    m = em.m
    size = info.size if info.size is not None else m.extent(info)
    fields = sorted(flat_fields(em, info), key=lambda f: f[0])
    lines = [f"struct {info.name} {{  /* size 0x{size:X} */"]
    cur = 0
    for off, fsize, ctype, name in fields:
        if off < cur:
            continue  # overlaps an earlier field
        if off > cur:
            lines.append(f"    char unk_{cur:X}[0x{off - cur:X}];")
        lines.append(f"    /* 0x{off:X} */ {ctype} {name};")
        cur = off + fsize
    if size > cur:
        lines.append(f"    char unk_{cur:X}[0x{size - cur:X}];")
    if len(lines) == 1:
        lines.append("    char unk_0[1];")
    lines.append("};")
    return "\n".join(lines)


def generate() -> str:
    m = Model()
    em = Emitter(m)
    out = [PRELUDE]
    classes = []
    for path, info in sorted(m.classes.items()):
        # nested and template classes have names m2c's demangler produces with
        # "::" or "<>", which cannot be struct tags in C
        if len(path) != 1 or "<" in path[0] or em.anonymous(path) or not m.is_class(path):
            continue
        classes.append(info)
    for info in classes:
        out.append(f"typedef struct {info.name} {info.name};")
    out.append("")
    for info in classes:
        if info.has_code or info.size is not None or info.accesses:
            out.append(struct_text(em, info))
            out.append("")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-o", "--output", type=Path, default=ROOT / "build" / "m2c" / "context.c")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate())
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
