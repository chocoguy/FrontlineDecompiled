def write(path: Path, text: str, force: bool) -> bool:
    if path.exists():
        old = path.read_text()
        if not old.startswith(GENERATED_MARK):
            print(f"skip {path} (hand-written)")
            return False
        if old == text:
            return False
        if not force:
            print(f"skip {path} (exists; use --force)")
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


def stub(f: Func, cls_name: Optional[str]) -> str:
    """An empty definition of `f`, so the compiler emits its mangled name."""
    d = f.sym
    params = ", ".join(f"{render_param(p, k)}" for k, p in enumerate(d.params))
    tail = " const" if d.const else ""
    q = "::".join([*d.scope, d.name])
    if d.special == "ct":
        return f"{q}({params}) {{}}"
    if d.special == "dt":
        return f"{'::'.join(d.scope)}::~{cls_name}() {{}}"
    if d.special == "conv":
        return f"{q}(){tail} {{ return *({render(d.conv_type)}*)0; }}"
    ret = ret_type(f)
    body = "" if ret == "void" else " return 0;"
    return f"{ret} {q}({params}){tail} {{{body}}}"


def render_param(t: Type, k: int) -> str:
    from cwdemangle import declarator
    return declarator(t, f"p{k}") if not (t.kind == "builtin" and t.name == "...") else "..."


def compile_check(em: Emitter, inc: Path) -> int:
    """Define every declared function in one TU including all headers, compile it
    with MWCC and compare the emitted mangled names; also assert class sizes."""
    import tempfile
    mw = ROOT / "build/compilers/GC/1.3.2/mwcceppc.exe"
    wibo = ROOT / "build/tools/wibo"
    dtk = ROOT / "build/tools/dtk"
    m = em.m
    src = [f'#include "{h}"' for h in sorted(em.headers)]
    # definitions need complete by-value parameter types: give the homeless
    # ones (only forward-declared in the headers) empty bodies here
    for path, info in sorted(m.classes.items()):
        if path in em.home_header or em.anonymous(path) or m.is_enum(info):
            continue
        if any(m.is_class(path[:k]) for k in range(1, len(path))):
            continue
        last = path[-1]
        op, cl = em.scope_open(path)
        if any("<" in x for x in path):
            continue
        if info.by_value and m.is_class(path):
            src.append(f"{op}{em.class_key(info)} {last} {{}};{cl.strip()}")
    expected: Set[str] = set()
    skipped_ct = 0
    skipped_tmpl = 0
    funcs: List[Tuple[Func, Optional[ClassInfo]]] = []
    for info in m.classes.values():
        if info.path in em.home_header:
            funcs += [(f, info) for f in info.methods]
    for fs in m.free_funcs.values():
        funcs += [(f, None) for f in fs if f.raw.scope != "local"]
    declared = set().union(*em.expected.values()) if em.expected else set()
    for f, info in funcs:
        if f.sym.mangled not in declared:
            continue
        if f.sym.special == "ct" and info:
            # an empty constructor needs default-constructible bases
            if any(any(g.sym.special == "ct" for g in m.classes[b].methods) and
                   not any(g.sym.special == "ct" and not g.sym.params for g in m.classes[b].methods)
                   for b, _ in info.bases if b in m.classes):
                skipped_ct += 1
                continue
        if any(by_value and any("<" in x for x in type_path(c))
               for p in f.sym.params for c, by_value in p.classes()):
            skipped_tmpl += 1
            continue
        src.append(stub(f, info.name.split("<")[0] if info else None))
        expected.add(f.sym.mangled)
    size_checks = []
    for h in sorted(em.sizes):
        for name, size, source in em.sizes[h]:
            src.append(f"extern const unsigned long gen_sizeof_{len(size_checks)} = sizeof({name});")
            size_checks.append((name, size, source))
    for k, (cname, fname, off) in enumerate(em.offsets):
        src.append(f"extern const unsigned long gen_offset_{k} = "
                   f"(unsigned long)&((({cname}*)0)->{fname});")
    tmp = Path(tempfile.mkdtemp())
    tu = tmp / "check.cpp"
    tu.write_text("\n".join(src) + "\n")
    obj = tmp / "check.o"
    r = subprocess.run([str(wibo), str(mw), "-nodefaults", "-proc", "gekko", "-O0",
                        "-Cpp_exceptions", "on", "-RTTI", "on", "-enum", "int", "-maxerrors", "40",
                        "-nosyspath", "-i", str(inc), "-c", str(tu), "-o", str(obj)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print((r.stdout + r.stderr)[:6000])
        print(f"compile failed (TU kept at {tu})")
        return 1
    info = subprocess.run([str(dtk), "elf", "info", str(obj)], capture_output=True, text=True).stdout
    got = set(re.findall(r"\|\s+(\S+)\s*$", info, re.M))
    missing = sorted(expected - got)
    for n in missing[:20]:
        print(f"not produced: {n}")
    values = read_u32_symbols(obj.read_bytes(), "gen_sizeof_")
    bad_sizes = []
    for k, (name, size, source) in enumerate(size_checks):
        actual = values.get(f"gen_sizeof_{k}")
        if actual != size:
            bad_sizes.append((name, size, actual, source))
    offs = read_u32_symbols(obj.read_bytes(), "gen_offset_")
    bad_offsets = [(c, f, o, offs.get(f"gen_offset_{k}")) for k, (c, f, o) in enumerate(em.offsets)
                   if offs.get(f"gen_offset_{k}") != o]
    for c, f, o, actual in bad_offsets[:20]:
        print(f"offset mismatch: {c}::{f} expected 0x{o:X}, header gives "
              + (f"0x{actual:X}" if actual is not None else "?"))
    print(f"{len(em.offsets) - len(bad_offsets)}/{len(em.offsets)} inferred field offsets match")
    for name, size, actual, source in bad_sizes:
        print(f"size mismatch: {name}: binary 0x{size:X} ({source}), header gives "
              + (f"0x{actual:X}" if actual is not None else "?"))
    print(f"verified {len(expected) - len(missing)}/{len(expected)} mangled names "
          f"({skipped_ct} constructors, {skipped_tmpl} template-by-value functions not checked); "
          f"{len(size_checks) - len(bad_sizes)}/{len(size_checks)} class sizes match")
    return len(missing) + len(bad_sizes) + len(bad_offsets)


def read_u32_symbols(data: bytes, prefix: str) -> Dict[str, int]:
    """Values of 4-byte data symbols in a relocatable big-endian ELF."""
    import struct
    shoff = struct.unpack(">I", data[0x20:0x24])[0]
    es, n, si = struct.unpack(">HHH", data[0x2E:0x34])
    S = [struct.unpack(">10I", data[shoff + i * es:shoff + i * es + 40]) for i in range(n)]
    out = {}
    for sec in S:
        if sec[1] != 2:
            continue
        strtab = S[sec[6]]
        for j in range(sec[5] // 16):
            nm, value, size, info, other, shndx = struct.unpack(
                ">IIIBBH", data[sec[4] + j * 16:sec[4] + j * 16 + 16])
            name = data[strtab[4] + nm:data.index(b"\0", strtab[4] + nm)].decode()
            if name.startswith(prefix) and 0 < shndx < len(S):
                off = S[shndx][4] + value
                out[name] = struct.unpack(">I", data[off:off + 4])[0]
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "include")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    m = Model()
    em = Emitter(m)
    written = 0
    texts = {h: em.render_header(h) for h in sorted(em.headers)}
    if not args.check:
        written += write(args.out / "types.h", TYPES_H, args.force)
        written += write(args.out / "game_types.h", em.game_types(), args.force)
        for h, text in texts.items():
            written += write(args.out / h, text, args.force)
        print(f"wrote {written} file(s) to {args.out}")
    else:
        # check against a fresh copy so hand edits in include/ don't matter
        import tempfile
        tmp = Path(tempfile.mkdtemp())
        (tmp / "types.h").write_text(TYPES_H)
        (tmp / "game_types.h").write_text(em.game_types())
        for h, text in texts.items():
            (tmp / h).parent.mkdir(parents=True, exist_ok=True)
            (tmp / h).write_text(text)
        sys.exit(1 if compile_check(em, tmp) else 0)
    classes = [c for c in m.classes.values() if c.path in em.home_header]
    print(f"{len(classes)} classes in {len(em.headers)} headers; "
          f"{sum(1 for c in classes if c.size is not None)} with known size, "
          f"{sum(1 for c in classes if c.vt_sym)} with vtables, "
          f"{sum(len(c.bases) > 0 for c in classes)} with bases")
    for w in m.warnings[:20]:
        print("warning:", w)


if __name__ == "__main__":
    main()
