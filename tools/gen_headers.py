#!/usr/bin/env python3

###
# Generate skeleton C++ headers from the retail symbols.
#
# Sources of information:
# - mangled names (tools/cwdemangle.py): classes, namespaces, methods, params
# - vtables in the retail ELF: which methods are virtual and their slot order
# - RTTI records: base classes and their offsets
# - disassembly (tools/asmindex.py): sizes passed to operator new, vtable
#   pointer offset, field offsets/widths accessed through `this`, whether a
#   method uses `this` (static or not), rough return kinds
#
# One header per C++ source unit under game/, ea/ and movie/ is written to
# include/<unit>.h, plus include/game_types.h for types with no home unit.
# Everything inferred from code (fields, return types, static-ness) is a
# guess to be corrected while decompiling; names, parameter types, virtual
# order, bases and sizes come straight from the binary.
#
#   python tools/gen_headers.py            # write headers (refuses to overwrite)
#   python tools/gen_headers.py --force    # overwrite existing generated headers
#   python tools/gen_headers.py --check    # compile every header with MWCC and
#                                          # verify mangled names and sizes
###

import argparse
import re
import subprocess
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))
from asmindex import Access, AsmIndex, return_kind, reads_before_write, this_accesses, new_sizes  # noqa: E402
from cwdemangle import (Symbol, Type, class_display, demangle, qualified_name,  # noqa: E402
                        render, template_args)
from elfdata import Program, Sym  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
VERSION = "GMFE69"
TARGETS = ("game/", "ea/", "movie/")
GENERATED_MARK = "// Generated by tools/gen_headers.py"

Path_ = Tuple[str, ...]


@dataclass
class Func:
    sym: Symbol
    raw: Sym
    unit: Optional[str]
    ret: str = "void"
    static: bool = False
    virtual: bool = False

    @property
    def path(self) -> Path_:
        return self.sym.scope


@dataclass
class ClassInfo:
    path: Path_
    methods: List[Func] = field(default_factory=list)
    vtable: List[object] = field(default_factory=list)     # Func | "pure" | None
    secondary: List[Tuple[int, List[object]]] = field(default_factory=list)
    vt_sym: Optional[Sym] = None
    rtti_sym: Optional[Sym] = None
    all_bases: List[Tuple[Path_, int]] = field(default_factory=list)
    bases: List[Tuple[Path_, int]] = field(default_factory=list)
    size: Optional[int] = None
    size_source: str = ""
    vptr: Optional[int] = None
    accesses: List = field(default_factory=list)
    static_data: List[Tuple[str, Sym]] = field(default_factory=list)
    by_value: bool = False
    by_ref: bool = False
    home: Optional[str] = None
    header_only: bool = False        # all code inline (weak): gets its own header
    namespace: bool = False          # only "static methods", never a type: a namespace

    @property
    def name(self) -> str:
        return self.path[-1]

    @property
    def is_template(self) -> bool:
        return any("<" in p for p in self.path)

    @property
    def has_code(self) -> bool:
        return bool(self.methods or self.vt_sym or self.rtti_sym)


def linked_units() -> List[str]:
    ninja = (ROOT / "build.ninja").read_text()
    start = re.search(rf"^build build/{VERSION}/Moh2RelGC\.elf( \| \S+)?: link", ninja, re.M).start()
    block = ninja[start:ninja.index("\n\n", start)]
    # split objects (obj/) and compiled sources (src/); dtk still writes asm for both
    return re.findall(rf"build/{VERSION}/(?:obj|src)/(\S+)\.o", block)


def int_params(params: List[Type]) -> int:
    """General purpose registers used by these parameters."""
    n = 0
    for t in params:
        if t.kind == "builtin" and t.name in ("float", "double", "long double"):
            continue
        if t.kind == "builtin" and t.name == "long long":
            n += 2 + (n % 2)
            continue
        if t.kind == "builtin" and t.name == "...":
            continue
        n += 1
    return n


class Model:
    def __init__(self):
        self.prog = Program(ROOT, VERSION)
        units = linked_units()
        self.asm = AsmIndex([ROOT / "build" / VERSION / "asm" / f"{u}.s" for u in units
                             if (ROOT / "build" / VERSION / "asm" / f"{u}.s").exists()])
        self.classes: Dict[Path_, ClassInfo] = {}
        self.free_funcs: Dict[str, List[Func]] = defaultdict(list)
        self.c_funcs: Dict[str, List[Sym]] = defaultdict(list)
        self.globals: Dict[str, List[Tuple[Optional[Symbol], Sym]]] = defaultdict(list)
        self.templates: Dict[Path_, List[str]] = defaultdict(list)   # template path -> notes
        self.func_by_addr: Dict[int, Func] = {}
        self.warnings: List[str] = []
        self._extent: Dict[Path_, int] = {}
        self._collect()
        self._vtables_and_rtti()
        self._sizes()
        self._analyze_methods()
        self._layout()
        self._homes()

    def cls(self, path: Path_) -> ClassInfo:
        if path not in self.classes:
            self.classes[path] = ClassInfo(path)
        return self.classes[path]

    def note_types(self, params: List[Type]) -> None:
        for t in params:
            for c, by_value in t.classes():
                info = self.cls(type_path(c))
                if by_value:
                    info.by_value = True
                else:
                    info.by_ref = True

    # ------------------------------------------------------------ symbols
    def _collect(self) -> None:
        seen: Set[str] = set()
        for s in self.prog.syms:
            if s.name.startswith(("@", "lbl_", "gap_")) or s.name in seen:
                continue
            unit = self.prog.unit_of(s.addr)
            if not unit or not unit.startswith(TARGETS):
                continue
            seen.add(s.name)
            d = demangle(s.name)
            if d is None:
                if s.kind == "function":
                    if not s.name.startswith("__sinit_"):
                        self.c_funcs[unit].append(s)
                elif s.kind == "object" and s.scope != "local":
                    self.globals[unit].append((None, s))
                continue
            if d.special in ("vt", "rtti"):
                continue
            if d.is_function:
                f = Func(d, s, unit)
                self.func_by_addr.setdefault(s.addr, f)
                self.note_types(d.params)
                if d.scope:
                    if any("<" in p for p in d.scope) or "<" in d.name:
                        self.templates[d.scope or (d.name,)].append(f"{s.name}")
                        continue
                    self.cls(d.scope).methods.append(f)
                else:
                    if "<" in d.name:
                        self.templates[(d.name,)].append(s.name)
                        continue
                    self.free_funcs[unit].append(f)
            else:
                if d.scope:
                    self.cls(d.scope).static_data.append((d.name, s))
                    self.globals[unit].append((d, s))

    # ------------------------------------------------------------ vtables / RTTI
    def _target_func(self, addr: int) -> Optional[Func]:
        if addr in self.func_by_addr:
            return self.func_by_addr[addr]
        for s in self.prog.by_addr.get(addr, []):
            m = re.match(r"^@(-?\d+)@(.*)$", s.name)     # MI thunk: @offset@target
            if m:
                d = demangle(m.group(2))
                for t in self.prog.by_name.get(m.group(2), []):
                    if t.addr in self.func_by_addr:
                        return self.func_by_addr[t.addr]
        return None

    def _vtables_and_rtti(self) -> None:
        p = self.prog
        rtti_at: Dict[int, Path_] = {}
        for s in p.syms:
            if s.name.startswith("__RTTI__"):
                d = demangle(s.name)
                if d and d.scope:
                    rtti_at[s.addr] = d.scope
                    if not self.cls(d.scope).rtti_sym:
                        self.cls(d.scope).rtti_sym = s
        for s in p.syms:
            if not s.name.startswith("__vt__"):
                continue
            d = demangle(s.name)
            if not d or not d.scope:
                continue
            info = self.cls(d.scope)
            if info.vt_sym:           # weak copy in another unit
                continue
            info.vt_sym = s
            tables: List[Tuple[int, List[object]]] = []
            for o in range(0, s.size, 4):
                a = s.addr + o
                tgt = p.pointer_at(a)
                if tgt is not None and tgt in rtti_at:
                    tables.append((-(p.read_u32(a + 4) or 0) & 0xFFFFFFFF, []))
                    continue
                if not tables or a == s.addr + 4 or (tables and p.pointer_at(a - 4) in rtti_at):
                    continue
                if tgt is None:
                    tables[-1][1].append("pure" if p.read_u32(a) == 0 else None)
                else:
                    tables[-1][1].append(self._target_func(tgt))
            if tables:
                info.vtable = tables[0][1]
                info.secondary = [(off - 0x100000000 if off & 0x80000000 else off, t)
                                  for off, t in tables[1:]]
        # bases from RTTI base lists
        done: Set[Path_] = set()
        for addr, path in rtti_at.items():
            info = self.classes[path]
            if path in done:          # weak copies of the same RTTI in many units
                continue
            done.add(path)
            bl = p.pointer_at(addr + 4)
            if bl is None:
                continue
            k = 0
            while True:
                tgt = p.pointer_at(bl + k)
                if tgt is None or tgt not in rtti_at:
                    break
                off = p.read_u32(bl + k + 4) or 0
                info.all_bases.append((rtti_at[tgt], off))
                k += 8
        for info in self.classes.values():
            direct = []
            for b, off in info.all_bases:
                indirect = any(b2 != b and any(bb == b and o2 + boff == off
                                               for bb, boff in self.classes[b2].all_bases)
                               for b2, o2 in info.all_bases if b2 in self.classes)
                if not indirect:
                    direct.append((b, off))
            info.bases = sorted(direct, key=lambda x: x[1])

    # ------------------------------------------------------------ sizes
    def _sizes(self) -> None:
        for ct, sizes in new_sizes(self.asm).items():
            d = demangle(ct)
            if d and d.scope in self.classes:
                info = self.classes[d.scope]
                if len(sizes) == 1:
                    info.size, info.size_source = next(iter(sizes)), "operator new"
                else:
                    self.warnings.append(f"{'::'.join(d.scope)}: conflicting new sizes {sorted(sizes)}")
        # global instances: r3 = &object right before a constructor call
        addrs = sorted(self.asm.insns)
        for k, a in enumerate(addrs):
            i = self.asm.insns[a]
            if i.mn != "bl" or not i.ops or not i.ops[0].startswith("__ct__"):
                continue
            d = demangle(i.ops[0])
            if not d or d.scope not in self.classes or self.classes[d.scope].size:
                continue
            for back in range(1, 6):
                p = self.asm.insns.get(addrs[k - back])
                if p is None:
                    break
                if p.mn == "addi" and p.ops[0] == "r3":
                    m = re.match(r"^(\S+?)@(l|sda21)$", p.ops[2])
                    syms = self.prog.by_name.get(m.group(1), []) if m else []
                    if syms and syms[0].size and syms[0].kind == "object":
                        info = self.classes[d.scope]
                        if info.size is None or syms[0].size < info.size:
                            info.size, info.size_source = syms[0].size, f"global {syms[0].name} (upper bound)"
                    break
                if "r3" in p.ops[:1] or p.mn == "bl":
                    break

    # ------------------------------------------------------------ per-method analysis
    def _analyze_methods(self) -> None:
        slot_funcs: Dict[Tuple[Path_, int], List[Func]] = defaultdict(list)
        virtuals: Set[int] = set()
        for info in self.classes.values():
            for t in [info.vtable] + [s for _, s in info.secondary]:
                for f in t:
                    if isinstance(f, Func):
                        virtuals.add(f.raw.addr)
        for info in self.classes.values():
            for f in info.methods:
                body = self.asm.function(f.raw.addr, f.raw.size)
                f.virtual = f.raw.addr in virtuals
                special = f.sym.special in ("ct", "dt")
                certain_member = f.virtual or special or f.sym.const or f.sym.special in ("op", "conv")
                if not certain_member and body:
                    n = int_params(f.sym.params)
                    if n < 8 and not reads_before_write(body, 3 + n) and reads_before_write(body, 3):
                        f.static = True
                if not special:
                    f.ret = return_kind(body) if body else "void"
                if not f.static and body:
                    acc, vps, subs = this_accesses(body)
                    info.accesses.extend(acc)
                    # &this->member taken: the class reaches at least that far
                    info.accesses.extend(Access(o, 1, "sub", False) for o in subs if 0 <= o < 0x10000)
                    if f.sym.special == "ct":
                        for off, vt in vps:
                            vd = demangle(vt.split("+")[0])
                            if vd and vd.scope == info.path and "+" not in vt:
                                info.vptr = off
        for funcs in self.free_funcs.values():
            for f in funcs:
                body = self.asm.function(f.raw.addr, f.raw.size)
                f.ret = return_kind(body) if body else "void"
        # overriding functions must agree on return type: unify along slots
        for info in self.classes.values():
            for idx, f in enumerate(info.vtable):
                if isinstance(f, Func):
                    slot_funcs[(self._slot_root(info.path, idx), idx)].append(f)
        rank = {"void": 0, "bool": 1, "float": 2, "int": 3}
        for fs in slot_funcs.values():
            best = max((f.ret for f in fs), key=lambda r: rank[r])
            for f in fs:
                f.ret = best
        self.slot_funcs = slot_funcs

    def _slot_root(self, path: Path_, idx: int) -> Path_:
        """The class that introduced vtable slot `idx` of `path` (via primary bases)."""
        info = self.classes.get(path)
        while info:
            prim = self.primary_base(info)
            if prim is None or idx >= len(prim.vtable):
                return info.path
            info = prim
        return path

    def primary_base(self, info: ClassInfo) -> Optional[ClassInfo]:
        for b, off in info.bases:
            if off == 0 and b in self.classes:
                return self.classes[b]
        return None

    # ------------------------------------------------------------ layout
    def own_start(self, info: ClassInfo) -> int:
        end = 0
        for b, off in info.bases:
            end = max(end, off + self.extent(self.classes[b]))
        return end

    def extent(self, info: ClassInfo, _stack=()) -> int:
        if info.size is not None:
            return info.size
        if info.path in _stack:
            return 0
        if info.path in self._extent:
            return self._extent[info.path]
        self._extent[info.path] = val = self._compute_extent(info, _stack)
        return val

    def _compute_extent(self, info: ClassInfo, _stack) -> int:
        end = 0
        for b, off in info.bases:
            end = max(end, off + self.extent(self.classes[b], _stack + (info.path,)))
        for a in info.accesses:
            end = max(end, a.offset + a.width)
        if self.introduces_vptr(info) and info.vptr is not None:
            end = max(end, info.vptr + 4)
        elif self.introduces_vptr(info):
            end = max(end, self.own_start(info) + 4)
        return (end + 3) & ~3

    def introduces_vptr(self, info: ClassInfo) -> bool:
        if not info.vt_sym:
            return False
        return not any(self.classes[b].vt_sym for b, _ in info.bases if b in self.classes)

    def _layout(self) -> None:
        self._extent: Dict[Path_, int] = {}
        # push accesses made by derived classes inside a base's range down to the base
        order = sorted(self.classes.values(), key=lambda c: -len(c.all_bases))
        for info in order:
            start = self.own_start(info)
            keep = []
            for a in info.accesses:
                if a.offset >= start or not info.bases:
                    keep.append(a)
                    continue
                for b, off in info.bases:
                    base = self.classes[b]
                    if off <= a.offset < off + self.extent(base):
                        base.accesses.append(type(a)(a.offset - off, a.width, a.kind, a.store, a.pointer))
                        break
            info.accesses = keep

    # ------------------------------------------------------------ homes
    def _homes(self) -> None:
        for info in self.classes.values():
            units = Counter(f.unit for f in info.methods if f.raw.scope != "weak")
            if not units and (info.methods or info.vt_sym):
                info.header_only = True
                units = Counter(f.unit for f in info.methods)
            if units:
                info.home = units.most_common(1)[0][0]
            elif info.vt_sym:
                info.home = self.prog.unit_of(info.vt_sym.addr)
            elif info.rtti_sym:
                info.home = self.prog.unit_of(info.rtti_sym.addr)
            if info.home and not info.home.startswith(TARGETS):
                info.home = None
        # outer scopes: a path prefix is a class if anything treats it as one
        for path in list(self.classes):
            for k in range(1, len(path)):
                self.cls(path[:k])
        # scopes that are really namespaces: their "methods" become free functions
        for info in list(self.classes.values()):
            if info.methods and not (info.vt_sym or info.rtti_sym or info.by_value or info.by_ref
                                     or info.size is not None) \
                    and all(f.static for f in info.methods) \
                    and not any(f.sym.special or f.sym.const for f in info.methods):
                for f in info.methods:
                    f.static = False
                    self.free_funcs[f.unit].append(f)
                info.methods = []
                info.namespace = True

    def is_class(self, path: Path_) -> bool:
        info = self.classes.get(path)
        if any(x.startswith("@unnamed@") for x in path):
            return False
        if info and info.namespace:
            return False
        return bool(info and (info.has_code or info.by_value or info.by_ref or info.size))

    def is_enum(self, info: ClassInfo) -> bool:
        return (not info.has_code and info.by_value and not info.by_ref
                and not info.static_data and not info.is_template)


def tarjan(graph: Dict[str, Set[str]]) -> List[List[str]]:
    index, low, stack, on, out = {}, {}, [], set(), []
    counter = [0]

    def visit(v: str) -> None:
        index[v] = low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        on.add(v)
        for w in graph.get(v, ()):
            if w not in graph:
                continue
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w == v:
                    break
            out.append(comp)

    sys.setrecursionlimit(10000)
    for v in graph:
        if v not in index:
            visit(v)
    return out


def type_path(t: Type) -> Path_:
    return (*t.scope, class_display(t))


# ====================================================================== emit

FIELD_TYPES = {(1, "int"): "u8", (2, "int"): "u16", (2, "sint"): "s16", (4, "int"): "u32",
               (4, "float"): "f32", (8, "double"): "f64", (8, "float2"): "f32"}


def ret_type(f: Func) -> str:
    if f.sym.name in ("operator new", "operator new[]"):
        return "void*"
    if f.sym.name in ("operator delete", "operator delete[]"):
        return "void"
    return f.ret


def header_path(unit: str) -> str:
    return re.sub(r"\.[A-Za-z]+$", ".h", unit)


def guard(rel: str) -> str:
    return "_" + re.sub(r"[^A-Za-z0-9]", "_", rel).upper() + "_"


class Emitter:
    def __init__(self, m: Model):
        self.m = m
        self.headers: Dict[str, List[ClassInfo]] = defaultdict(list)
        for info in m.classes.values():
            if info.home and not info.is_template and m.is_class(info.path) and info.has_code \
                    and not self.anonymous(info.path):
                if info.header_only:
                    top = info.home.split("/")[0]
                    name = re.sub(r"[^A-Za-z0-9_]", "_", "_".join(info.path))
                    self.headers[f"{top}/{name}.h"].append(info)
                else:
                    self.headers[header_path(info.home)].append(info)
        for unit in set(m.free_funcs) | set(m.c_funcs):
            self.headers.setdefault(header_path(unit), [])
        self.redirect: Dict[str, str] = {}
        self.home_header = {c.path: h for h, cs in self.headers.items() for c in cs}
        self._merge_cycles()
        self.expected: Dict[str, Set[str]] = defaultdict(set)   # header -> mangled names
        self.sizes: Dict[str, List[Tuple[str, int, str]]] = defaultdict(list)
        self.offsets: List[Tuple[str, str, int]] = []     # class, field, offset
        self.skipped: Dict[str, List[str]] = defaultdict(list)

    # -------------------------------------------------- types
    @staticmethod
    def anonymous(path: Path_) -> bool:
        return any(x.startswith("@unnamed@") for x in path)

    def class_key(self, info: ClassInfo) -> str:
        return "class" if info.has_code else "struct"

    def spelled(self, t: Type) -> str:
        return render(t)

    def mentions_unemittable(self, types: List[Type]) -> bool:
        for t in types:
            for c, _ in t.classes():
                p = type_path(c)
                if any("<" in x for x in p[:-1]) or self.anonymous(p):
                    return True
        return False

    def decl(self, f: Func, cls: Optional[ClassInfo]) -> str:
        s = f.sym
        params = ", ".join(self.spelled(p) for p in s.params)
        tail = " const" if s.const else ""
        if s.special == "ct":
            return f"{cls.name.split('<')[0]}({params});"
        if s.special == "dt":
            return f"{'virtual ' if f.virtual else ''}~{cls.name.split('<')[0]}();"
        if s.special == "conv":
            return f"{'virtual ' if f.virtual else ''}{s.name}(){tail};"
        prefix = ("static " if f.static else "") + ("virtual " if f.virtual else "")
        return f"{prefix}{ret_type(f)} {s.name}({params}){tail};"

    # -------------------------------------------------- class body
    def fields(self, info: ClassInfo, start: int, end: Optional[int]) -> List[Tuple[int, int, str]]:
        """(offset, size, declaration) for inferred fields in [start, end)."""
        by_off: Dict[int, Counter] = defaultdict(Counter)
        ptr: Set[int] = set()
        for a in info.accesses:
            if a.kind == "sub" or a.offset < start or (end is not None and a.offset + a.width > end):
                continue
            by_off[a.offset][(a.width, a.kind)] += 1
            if a.pointer:
                ptr.add(a.offset)
        out = []
        cur = start
        for off in sorted(by_off):
            if off < cur:
                continue
            width, kind = max(by_off[off].items(), key=lambda kv: (kv[0][0], kv[1]))[0]
            if off % min(width, 4):
                continue
            ty = FIELD_TYPES[(width, kind)]
            name = f"field_0x{off:X}"
            if (width, kind) == (4, "int") and off in ptr:
                ty = "void*"
            if kind == "float2":
                out.append((off, 8, f"{ty} {name}[2];"))
            elif kind == "double":
                # lfd/stfd is also how CodeWarrior copies 8-byte blocks; a real
                # f64 member would force 8-byte alignment of the whole class
                out.append((off, 8, f"u32 {name}[2];  // lfd/stfd: f64 or 8-byte copy"))
            else:
                out.append((off, width, f"{ty} {name};"))
            cur = off + width
        return out

    def body(self, info: ClassInfo, header: str) -> List[str]:
        m = self.m
        lines: List[str] = []
        start = m.own_start(info)
        size = info.size
        end = size if size is not None else m.extent(info)
        vptr_here = m.introduces_vptr(info)
        vptr_at = info.vptr if vptr_here else None
        if vptr_here and vptr_at is None:
            vptr_at = start
        if vptr_at is not None and vptr_at < start:
            self.m.warnings.append(f"{'::'.join(info.path)}: vptr 0x{vptr_at:X} inside base")
            vptr_at = start
        flds = self.fields(info, start, end)
        if vptr_at is not None:
            flds = [f for f in flds if not (f[0] < vptr_at + 4 and f[0] + f[1] > vptr_at)]

        # nested types declared inside the class
        nested = [c for c in m.classes.values()
                  if c.path[:-1] == info.path and m.is_class(c.path)]
        pub = ["public:"]
        for c in sorted(nested, key=lambda c: c.name):
            if m.is_enum(c):
                pub.append(f"    enum {c.name} {{}};  // passed by value: enum (values unknown)")
            elif not c.is_template:
                pub.append(f"    {self.class_key(c)} {c.name};")

        # methods, split into virtual (in slot order) and the rest
        primary = m.primary_base(info)
        inherited = len(primary.vtable) if primary else 0
        introduced: List[str] = []
        for idx in range(inherited, len(info.vtable)):
            f = info.vtable[idx]
            if isinstance(f, Func) and f.path == info.path:
                introduced.append(self.member_line(f, info, header))
            elif f == "pure" or f is None or isinstance(f, Func):
                introduced.append(self.pure_line(info, idx))
        own_methods = sorted(info.methods, key=lambda f: f.raw.addr)
        intro_set = {id(f) for f in info.vtable[inherited:] if isinstance(f, Func)}
        others = [self.member_line(f, info, header) for f in own_methods if id(f) not in intro_set]
        others = [o for o in others if o]

        def field_lines(lo: int, hi: Optional[int]) -> List[str]:
            out, cur = [], lo
            for off, w, d in flds:
                if off < lo or (hi is not None and off >= hi):
                    continue
                if off > cur:
                    out.append(f"    /* 0x{cur:X} */ u8 unk_0x{cur:X}[0x{off - cur:X}];")
                out.append(f"    /* 0x{off:X} */ {d}")
                fname = re.search(r"(\w+)(\[\d+\])?;", d).group(1)
                self.offsets.append(("::".join(info.path), fname, off))
                cur = off + w
            if hi is not None and cur < hi:
                out.append(f"    /* 0x{cur:X} */ u8 unk_0x{cur:X}[0x{hi - cur:X}];")
            return out

        lines += pub
        if vptr_at is not None:
            lines += field_lines(start, vptr_at)
            lines.append(f"    // vtable pointer at 0x{vptr_at:X}")
            lines += [l for l in introduced if l]
            lines += field_lines(vptr_at + 4, end)
        else:
            lines += [l for l in introduced if l]
            lines += field_lines(start, end)
        lines += [l for l in others]
        for name, s in info.static_data:
            lines.append(f"    // static ? {name};  // 0x{s.addr:08X} size 0x{s.size:X}")
        return lines

    def member_line(self, f: Func, info: ClassInfo, header: str) -> Optional[str]:
        types = list(f.sym.params) + ([f.sym.conv_type] if f.sym.conv_type else [])
        comment = f"  // 0x{f.raw.addr:08X}"
        if self.mentions_unemittable(types):
            self.skipped[header].append(f.sym.mangled)
            return f"    // {self.decl(f, info)}{comment} (uses a type nested in a template)"
        self.expected[header].add(f.sym.mangled)
        return f"    {self.decl(f, info)}{comment}"

    def pure_line(self, info: ClassInfo, idx: int) -> str:
        """Slot with no implementation in this class: find the name in a subclass."""
        for f in self.m.slot_funcs.get((info.path, idx), []):
            params = ", ".join(self.spelled(p) for p in f.sym.params)
            tail = " const" if f.sym.const else ""
            if f.sym.special == "dt":
                return f"    virtual ~{info.name}() = 0;"
            return f"    virtual {f.ret} {f.sym.name}({params}){tail} = 0;"
        return f"    virtual void unknown_slot_{idx}() = 0;  // name unknown"

    # -------------------------------------------------- headers
    def scope_open(self, path: Path_) -> Tuple[str, str]:
        """Namespace wrappers for the namespace part of a class path."""
        ns = []
        for k in range(1, len(path)):
            if self.m.is_class(path[:k]):
                break
            ns.append(path[k - 1])
        return ("".join(f"namespace {n} {{\n" for n in ns), "}\n" * len(ns))

    def class_text(self, info: ClassInfo, header: str) -> str:
        m = self.m
        bases = []
        for b, off in info.bases:
            bases.append(f"public {'::'.join(b)}")
        # name as written: nested classes are defined out of line as Outer::Inner
        outer_cls = [k for k in range(1, len(info.path)) if m.is_class(info.path[:k])]
        if outer_cls:
            name = "::".join(info.path[outer_cls[0] - 1:])
        else:
            name = info.name
        head = f"{self.class_key(info)} {name}" + (f" : {', '.join(bases)}" if bases else "")
        meta = []
        if info.size is not None:
            meta.append(f"size 0x{info.size:X} ({info.size_source})")
        else:
            meta.append(f"size >= 0x{m.extent(info):X} (from field accesses)")
        if info.vt_sym:
            meta.append(f"vtable 0x{info.vt_sym.addr:08X}")
        lines = [f"// {'; '.join(meta)}", head + " {"] + self.body(info, header) + ["};"]
        if info.size is not None:
            self.sizes[header].append(("::".join(info.path), info.size, info.size_source))
        op, cl = self.scope_open(info.path)
        if outer_cls:
            op, cl = self.scope_open(info.path[:outer_cls[0]])
        return op + "\n".join(lines) + "\n" + cl

    def refs(self, infos: List[ClassInfo], funcs: List[Func]) -> Set[Path_]:
        out: Set[Path_] = set()
        types: List[Type] = []
        for f in funcs:
            types += f.sym.params
        for info in infos:
            for f in info.methods:
                types += f.sym.params
            for idx in range(len(info.vtable)):
                for f in self.m.slot_funcs.get((info.path, idx), [])[:1]:
                    types += f.sym.params
        for t in types:
            for c, _ in t.classes():
                out.add(type_path(c))
        return out

    def resolve(self, header: str) -> str:
        while header in self.redirect:
            header = self.redirect[header]
        return header

    def unit_items(self, header: str):
        m = self.m
        funcs, c_funcs, globs = [], [], []
        for unit in set(m.free_funcs) | set(m.c_funcs) | set(m.globals):
            if self.resolve(header_path(unit)) == header:
                funcs += m.free_funcs.get(unit, [])
                c_funcs += m.c_funcs.get(unit, [])
                globs += m.globals.get(unit, [])
        return funcs, c_funcs, globs

    def deps(self, header: str) -> Tuple[Set[str], Set[Path_]]:
        """Headers that must be included (complete types) and paths to forward-declare."""
        m = self.m
        infos = self.headers[header]
        unit_funcs, _, _ = self.unit_items(header)
        includes: Set[str] = set()
        defined = {c.path for c in infos}
        for info in infos:
            for b, _ in info.bases:
                if self.home_header.get(b) not in (None, header):
                    includes.add(self.home_header[b])
            for k in range(1, len(info.path)):
                h = self.home_header.get(info.path[:k])
                if h and h != header:
                    includes.add(h)
        fwd: Set[Path_] = set()
        for p in self.refs(infos, unit_funcs):
            if p in defined or any("<" in x for x in p) or self.anonymous(p):
                continue
            outer = [p[:k] for k in range(1, len(p)) if m.is_class(p[:k])]
            if outer:
                h = self.home_header.get(outer[0])
                if h and h != header:
                    includes.add(h)
                continue
            if p in self.home_header or not m.is_enum(m.classes.get(p, ClassInfo(p))):
                fwd.add(p)
        return includes, fwd

    def _merge_cycles(self) -> None:
        """Merge headers that would include each other into one header."""
        units = {header_path(u) for u in set(self.m.free_funcs) | set(self.m.c_funcs)}
        units |= {header_path(c.home) for cs in self.headers.values() for c in cs
                  if c.home and not c.header_only}
        while True:
            graph = {h: self.deps(h)[0] for h in self.headers}
            sccs = [c for c in tarjan(graph) if len(c) > 1]
            if not sccs:
                return
            for comp in sccs:
                target = min(comp, key=lambda h: (h not in units, h))
                for h in comp:
                    if h == target:
                        continue
                    self.headers[target] += self.headers.pop(h)
                    self.redirect[h] = target
            self.home_header = {c.path: h for h, cs in self.headers.items() for c in cs}

    def render_header(self, header: str) -> str:
        m = self.m
        infos = self.headers[header]
        unit_funcs, c_funcs, globs = self.unit_items(header)
        includes, fwd = self.deps(header)
        order = self.topo(infos)
        out = [GENERATED_MARK, f"// Skeleton for {header[:-2]}: names, parameter types, virtual order,",
               "// bases and sizes come from the retail binary; fields, return types and",
               "// `static` are inferred from code and need checking.",
               f"#ifndef {guard(header)}", f"#define {guard(header)}", "",
               '#include "types.h"', '#include "game_types.h"']
        out += [f'#include "{h}"' for h in sorted(includes)]
        out.append("")
        # classes defined below may be used before their definition
        for info in infos:
            if not any(m.is_class(info.path[:k]) for k in range(1, len(info.path))):
                fwd.add(info.path)
        fwd_lines = []
        for p in sorted(fwd):
            info = m.classes.get(p)
            key = self.class_key(info) if info else "struct"
            op, cl = self.scope_open(p)
            fwd_lines.append(f"{op}{key} {p[-1]};{(chr(10) + cl.rstrip()) if cl else ''}")
        if fwd_lines:
            out += fwd_lines + [""]
        for info in order:
            out.append(self.class_text(info, header))
        by_scope: Dict[Path_, List[Func]] = defaultdict(list)
        for f in unit_funcs:
            by_scope[f.sym.scope].append(f)
        for scope in sorted(by_scope):
            out.append("// Free functions" + (f" in namespace {'::'.join(scope)}" if scope else ""))
            out += [f"namespace {n} {{" for n in scope]
            for f in sorted(by_scope[scope], key=lambda f: f.raw.addr):
                if self.mentions_unemittable(f.sym.params):
                    out.append(f"// {f.ret} {f.sym.name}(...);  // 0x{f.raw.addr:08X} {f.sym.mangled}")
                    continue
                params = ", ".join(self.spelled(p) for p in f.sym.params)
                line = f"{ret_type(f)} {f.sym.name}({params});  // 0x{f.raw.addr:08X}"
                if f.raw.scope == "local":
                    out.append(f"// static {line}")
                    continue
                out.append(line)
                self.expected[header].add(f.sym.mangled)
            out += ["}"] * len(scope)
            out.append("")
        if c_funcs:
            out.append("// Unmangled (C linkage or file-static) functions; signatures unknown:")
            for s in sorted(c_funcs, key=lambda s: s.addr):
                out.append(f"//   {s.name}  0x{s.addr:08X} size 0x{s.size:X}"
                           + ("  (static)" if s.scope == "local" else ""))
            out.append("")
        g = [(d, s) for d, s in globs if d is None]
        if g:
            out.append("// Globals defined in this unit (types unknown):")
            for _, s in sorted(g, key=lambda x: x[1].addr):
                out.append(f"//   {s.name}  0x{s.addr:08X} size 0x{s.size:X}")
            out.append("")
        out.append(f"#endif")
        return "\n".join(out) + "\n"

    def topo(self, infos: List[ClassInfo]) -> List[ClassInfo]:
        paths = {c.path: c for c in infos}
        done: List[ClassInfo] = []
        seen: Set[Path_] = set()

        def visit(c: ClassInfo):
            if c.path in seen:
                return
            seen.add(c.path)
            for b, _ in c.bases:
                if b in paths:
                    visit(paths[b])
            for k in range(1, len(c.path)):
                if c.path[:k] in paths:
                    visit(paths[c.path[:k]])
            done.append(c)
        for c in sorted(infos, key=lambda c: (c.methods[0].raw.addr if c.methods else 0)):
            visit(c)
        return done

    def template_definition(self, info: ClassInfo) -> str:
        """Generic definition of a template class from one instantiation's vtable."""
        last = info.path[-1]
        base = last[:last.index("<")]
        args = [a.strip() for a in last[last.index("<") + 1:-1].split(",")]

        def subst(text: str) -> str:
            for i, a in enumerate(args):
                text = re.sub(rf"(?<![\w:]){re.escape(a)}(?!\w)", f"T{i}", text)
            return text
        lines = [f"template <{', '.join(f'class T{i}' for i in range(len(args)))}>",
                 f"class {base} {{", "public:"]
        for idx, slot in enumerate(info.vtable):
            impls = self.m.slot_funcs.get((info.path, idx), [])
            if not impls:
                lines.append(f"    virtual void unknown_slot_{idx}() = 0;")
                continue
            f = impls[0]
            if f.sym.special == "dt":
                lines.append(f"    virtual ~{base}();")
                continue
            params = ", ".join(render(p) for p in f.sym.params)
            pure = " = 0" if slot == "pure" else ""
            lines.append(subst(f"    virtual {f.ret} {f.sym.name}({params}){' const' if f.sym.const else ''}{pure};"))
        lines.append("};")
        return "\n".join(lines)

    def game_types(self) -> str:
        """Types with no home unit: enums, forward-declared structs, templates."""
        m = self.m
        lines = [GENERATED_MARK, "// Types referenced by the game that have no defining unit.",
                 "#ifndef _GAME_TYPES_H_", "#define _GAME_TYPES_H_", ""]
        groups: Dict[Tuple[str, ...], List[str]] = defaultdict(list)
        for p, info in sorted(m.classes.items()):
            if p in self.home_header or info.is_template or self.anonymous(p):
                continue
            outer = [p[:k] for k in range(1, len(p)) if m.is_class(p[:k])]
            if outer:
                continue  # declared inside its outer class
            if m.is_enum(info):
                decl = f"enum {p[-1]} {{}};  // passed by value: enum (values unknown)"
            elif m.is_class(p):
                decl = f"{self.class_key(info)} {p[-1]};"
            else:
                continue
            groups[p[:-1]].append(decl)
        # template forward declarations
        tmpl: Dict[Path_, List[str]] = {}
        for p, info in m.classes.items():
            last = p[-1]
            if "<" not in last or any("<" in x for x in p[:-1]):
                continue
            base = (*p[:-1], last[:last.index("<")])
            inner = last[last.index("<") + 1:-1]
            depth, args, cur = 0, [], ""
            for ch in inner:
                depth += ch == "<"
                depth -= ch == ">"
                if ch == "," and depth == 0:
                    args.append(cur.strip())
                    cur = ""
                else:
                    cur += ch
            args.append(cur.strip())
            kinds = ["int" if re.fullmatch(r"-?\d+", a) else "class" for a in args]
            tmpl[base] = kinds
        for base, kinds in sorted(tmpl.items()):
            params = ", ".join(f"{'int' if k == 'int' else 'class'} T{i}" for i, k in enumerate(kinds))
            groups[base[:-1]].append(f"template <{params}> class {base[-1]};")
        # templates used as base classes need a definition (vtable layout matters)
        used_as_base = {b for c in m.classes.values() if c.path in self.home_header
                        for b, _ in c.bases if "<" in b[-1]}
        for path in sorted(used_as_base):
            groups[path[:-1]].append(self.template_definition(m.classes[path]))
        for ns, decls in sorted(groups.items()):
            for n in ns:
                lines.append(f"namespace {n} {{")
            lines += decls
            lines += ["}"] * len(ns)
            lines.append("")
        lines.append("#endif")
        return "\n".join(lines) + "\n"


