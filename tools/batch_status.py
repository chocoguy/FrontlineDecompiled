#!/usr/bin/env python3

###
# Regenerate docs/progress_batch1.md from configure.py and objdiff's report.
#
#   python tools/batch_status.py            # batch 1 (units 1-100)
#   python tools/batch_status.py --batch 2  # batch 2 (units 101-200) -> docs/progress_batch2.md
#
# Notes written in the table's last column are kept.
###

import argparse
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BATCH = 100


def main() -> None:
    ap = argparse.ArgumentParser(description="Regenerate docs/progress_batchN.md")
    ap.add_argument("--batch", type=int, default=1)
    args = ap.parse_args()
    DOC = ROOT / "docs" / f"progress_batch{args.batch}.md"
    first = (args.batch - 1) * BATCH
    subprocess.run(["ninja", "build/GMFE69/report.json"], cwd=ROOT, capture_output=True)
    report = json.loads((ROOT / "build/GMFE69/report.json").read_text())
    units = {u["name"].split("/", 1)[1]: u for u in report["units"]}
    cfg = (ROOT / "configure.py").read_text()
    objects = re.findall(r'Object\((\w+), "([^"]+)"([^)]*)\)', cfg)[first:first + BATCH]

    notes = {}
    tail = ""
    if DOC.exists():
        old = DOC.read_text()
        if "\n## " in old:
            tail = old[old.index("\n## "):]
        for line in old.splitlines():
            cells = [c.strip() for c in line.strip("|").split("|")]
            if len(cells) >= 6 and cells[0].isdigit():
                notes[cells[1]] = cells[-1]

    rows = []
    totals = {"units": 0, "done": 0, "funcs": 0, "src": 0, "exact": 0}
    for i, (status, unit, opts) in enumerate(objects, first + 1):
        stem = re.sub(r"\.[A-Za-z]+$", "", unit)
        rep = units.get(stem, {})
        funcs = rep.get("functions", [])
        total = len(funcs)
        in_src = sum(1 for f in funcs if f.get("fuzzy_match_percent") is not None
                     and "metadata" in f and status != "NonMatching")
        exact = sum(1 for f in funcs if f.get("fuzzy_match_percent") == 100.0)
        if status == "Matching":
            state = "matching"
        elif status == "NonMatching":
            state = "todo"
        elif "partial=True" in opts:
            state = "partial"
        else:
            state = "equivalent"
        m = rep.get("measures", {})
        fuzzy = m.get("fuzzy_match_percent", 0.0)
        code = int(m.get("total_code", 0))
        totals["units"] += 1
        totals["funcs"] += total
        if state != "todo":
            totals["done"] += 1
            totals["exact"] += exact
        rows.append(f"| {i} | {unit} | {total} | 0x{code:X} | {state} | "
                    f"{'' if state == 'todo' else f'{fuzzy:.1f}% ({exact}/{total} exact)'} | "
                    f"{notes.get(unit, '')} |")

    text = [
        f"# Decompilation progress: batch {args.batch} "
        f"(units {first + 1}-{first + len(objects)} in link order)",
        "",
        "Generated by `tools/batch_status.py`; edit only the Notes column.",
        "",
        "Status: `todo`, `partial` (some functions still from the original via",
        "tools/partial_obj.py), `equivalent` (all code in src, verified with objdiff",
        "and review), `matching` (byte-identical). Match is objdiff's fuzzy match",
        "of the unit and the number of functions that compile byte-identically.",
        "",
        f"**{totals['done']} / {totals['units']} units started; "
        f"{totals['exact']} functions byte-identical.**",
        "",
        "| # | Unit | Functions | Code | Status | Match | Notes |",
        "|---|---|---|---|---|---|---|",
        *rows,
    ]
    DOC.write_text("\n".join(text) + "\n" + tail)
    print(f"{totals['done']}/{totals['units']} units started, {totals['exact']} exact functions")


if __name__ == "__main__":
    main()
