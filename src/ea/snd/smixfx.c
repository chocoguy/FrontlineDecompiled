// Size of each module record in a filter graph file, by type.
s32 filtermodsizetable[10] = {4, 8, 4, 4, 8, 8, 4, 8, 4, 4};

SNDFXSEND sndfx;
static s32 FXfilterindex;  // the graph's source module

f32* MIX_getwetbuffer(void) {
    return sndfx.buf;
}

// Runs the classic reverb over the send buffer and mixes it into the outputs.
void SNDMIXI_fxadd(int frames) {
    SNDFBSTATE* fb = sndfb;
    f32* bufA = &sndfx.buf[0xA0];
    f32* bufB = &sndfx.buf[0x140];
    f32* in = sndfx.buf;
    f32* out = sndfx.buf;
    int g;
    int m;

    sndfx.silent++;
    for (g = 0; g < 3; g++) {
        SNDFBSTATE* f = fb;
        for (m = 0; m < sndfxnummodules[g]; m++) {
            // Group 0 runs in place on the send; groups 1 and 2 branch off it.
            if (g == 1) {
                if (m == 0) {
                    out = bufA;
                } else if (m == 1) {
                    in = bufA;
                }
            } else if (g == 2) {
                if (m == 0) {
                    out = bufB;
                    in = sndfx.buf;
                } else if (m == 1) {
                    in = bufB;
                }
            }
            int left = frames;
            while (left > 0) {
                int n = left;
                if (f->wpos <= 0) {
                    f->wpos = f->len;
                }
                if (f->rpos <= 0) {
                    f->rpos = f->len;
                }
                if (f->wpos < left) {
                    n = f->wpos;
                }
                if (f->rpos < n) {
                    n = f->rpos;
                }
                int off = frames - left;
                MIXI_reverbblock(f, n, in + off, out + off);
                left -= n;
                f->wpos -= n;
                f->rpos -= n;
            }
            f++;
            fb++;
        }
    }
    for (int i = 0; i < sndmix.numOutputs; i++) {
        if (i != 5) {
            if ((i & 1) && sndfxnummodules[1] != 0) {
                sndmix.mix(frames, bufB, sndmix.out[i], 1.0f);
            } else if (sndfxnummodules[2] != 0) {
                sndmix.mix(frames, bufA, sndmix.out[i], 1.0f);
            } else {
                sndmix.mix(frames, sndfx.buf, sndmix.out[i], 1.0f);
            }
        }
    }
    memset(sndfx.buf, 0, frames * 4);
}

// Runs the filter graph's output chains and mixes them into the outputs.
void SNDMIXI_modlapifxadd(int frames) {
    int done[6] = {0, 0, 0, 0, 0, 0};
    f32* b0;
    f32* b1;

    sndfx.silent++;
    b0 = sndmix.buf[0];
    b1 = sndmix.buf[1];
    int ok = SNDI_getb(pheaderinfo + (validstructoutputs - 1) * 4 + 8, 4);
    if (ok) {
        SFILTER_initSOURCE((SRCSTATE*)pfilterlist[FXfilterindex], sndfx.buf);
    }
    if (ok) {
        for (int i = 0; i < sndmix.numOutputs; i++) {
            if (done[i] == 0) {
                SFILTER* f = phead[i + 1];
                if (f != NULL) {
                    f->process(f, frames, b0, b1, i + 1);
                    sndmix.mix(frames, b1, sndmix.out[i], 1.0f);
                    done[i] = 1;
                    s8* copy = tablecopyto[validstructoutputs - 1][sndmix.numOutputs - 1][i];
                    for (int j = 0; j < sndmix.numOutputs; j++) {
                        if (copy[j] >= 0) {
                            sndmix.mix(frames, b1, sndmix.out[copy[j]], 1.0f);
                            done[copy[j]] = 1;
                        }
                    }
                }
            }
        }
    }
    memset(sndfx.buf, 0, frames * 4);
}

void SNDMIXI_fxinit(MIXFXHEADER* hdr) {
    sndfx.silent = 3000;
    memset(sndfx.buf, 0, 0x280);
    if (hdr->type == 10) {
        FXfilterindex = 0;
        for (u8* p = plisthead; *p != 0; p += filtermodsizetable[*p] * 20) {
            FXfilterindex++;
        }
    }
}
